--      evenly across the 4 slots in that shift, doubled up like the
--      existing machines' 1st/2nd-shift-shaped numbers).
--   2. Apply it the same way as the original seed file — psql or pgAdmin,
--      directly against squirtle (POSTGRES_HOST in .env), not through
--      CI/CD. Remember to disable SSL mode in pgAdmin if that's still
--      needed for this server.
--   3. Idempotent: safe to re-run if you need to correct a value later —
--      ON CONFLICT means it updates in place rather than erroring or
--      duplicating rows.

